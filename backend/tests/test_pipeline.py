"""End-to-end pipeline run on the synthetic seeded organisation (dataset D1).

Functional evidence only: the seeded data are generated by the app and are
never used as accuracy evidence (paper Section VIII-A).
"""
import json
import os

from app import models
from app.ai import assignment_engine as ae, baseline_gate as bg, bigru, workload_engine

REPORT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results", "pipeline_v2.json")


def _run(db):
    issues = db.query(models.Issue).filter(models.Issue.status != "Done").all()
    out = []
    for issue in issues:
        out.append((issue, ae.recommend_for_issue(db, issue)))
    return out


def test_pipeline_invariants_v2(seeded_db):
    db = seeded_db
    # train the BiGRU on seeded windows so the risk gate is exercised end to end
    meta = bigru.train(workload_engine.build_sequences_for_training(db))
    results = _run(db)
    assert results, "seeded database has no active issues"

    opted_out = {e.id for e in db.query(models.Employee).filter(models.Employee.workload_opt_out == True).all()}  # noqa: E712
    n_rec = n_esc = n_cand = 0
    violations = []
    gate_status_seen = set()
    for issue, rec in results:
        for c in rec["candidates"]:
            n_cand += 1
            if c["score_version"] != ae.SCORE_VERSION:
                violations.append((issue.id, c["employee_id"], "score_version"))
            if c["score_breakdown"]["workload_penalty"] < -30.0 - 1e-9:
                violations.append((issue.id, c["employee_id"], "workload>30"))
            if c["employee_id"] in opted_out:
                violations.append((issue.id, c["employee_id"], "opted_out_scored"))
            if not 0 <= c["overall"] <= 100:
                violations.append((issue.id, c["employee_id"], "range"))
            g = c.get("recovery_risk_gate")
            if g:
                gate_status_seen.add(g["status"])
                if g["status"] == bg.DEMOTED and c["recovery_risk"] != c["baseline_recovery_risk"]:
                    violations.append((issue.id, c["employee_id"], "demoted_model_served"))
        if rec["no_suitable_candidate"]:
            n_esc += 1
            assert "R8" in rec["reason"]
        else:
            n_rec += 1
            best = next(c for c in rec["candidates"] if c["employee_id"] == rec["recommended_employee_id"])
            if best["excluded_by_rule"]:
                violations.append((issue.id, best["employee_id"], "excluded_recommended"))
            if best["overall"] < ae.MIN_VIABLE_SCORE or best["capacity"] < ae.MIN_CAPACITY:
                violations.append((issue.id, best["employee_id"], "below_viability"))

    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, "w") as f:
        json.dump({"dataset": "D1 (synthetic seeded organisation)", "score_version": ae.SCORE_VERSION,
                   "active_issues": len(results), "recommendations": n_rec, "escalations_R8": n_esc,
                   "candidate_entries": n_cand, "invariant_violations": violations,
                   "bigru_status": meta.get("status"), "risk_gate": meta.get("gate"),
                   "risk_gate_statuses_seen": sorted(gate_status_seen)}, f, indent=2, default=str)
    assert violations == []
    assert n_rec + n_esc == len(results)
